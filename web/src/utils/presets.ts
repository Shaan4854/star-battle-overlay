export function createEmptyGrid(size: number): number[][] {
  const grid: number[][] = []
  for (let r = 0; r < size; r++) {
    const row: number[] = []
    for (let c = 0; c < size; c++) {
      row.push(-1) // -1 means unassigned
    }
    grid.push(row)
  }
  return grid
}
